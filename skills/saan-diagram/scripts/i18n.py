def tr(context, template, *values):
    language = context.get("language", "zh-CN")
    message = EN.get(template, template) if language == "en" else template
    return message.format(*values) if values else message


def join_labels(context, labels, quoted=False):
    """Localize list punctuation without modifying the labels themselves."""
    english = context.get("language", "zh-CN") == "en"
    left, right = ('"', '"') if english else ("『", "』")
    return (", " if english else "、").join(
        left + label + right if quoted else label for label in labels
    )
